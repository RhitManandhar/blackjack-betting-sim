// The sections of the standalone HTML report (spec 10.8, plan 8.4). Every figure uses the
// dashboard's own formatters, so the report shows exactly what the screen shows.

const yesNo = (value: boolean): string => (value ? 'Yes' : 'No');
const range = (low: string, high: string): string => `95% CI ${low} to ${high}`;

function rulesRows(rules: RuleSet): Cell[][] {
  return [
    ['Decks', String(rules.decks)],
    ['Dealer soft 17', rules.soft17 === 'S17' ? 'Stands (S17)' : 'Hits (H17)'],
    ['Blackjack pays', rules.blackjackPayout],
    [
      'Double down on',
      DOUBLE_OPTIONS.find((option) => option.value === rules.doubleOn)?.label ?? rules.doubleOn,
    ],
    ['Double after split', yesNo(rules.doubleAfterSplit)],
    ['Late surrender', yesNo(rules.lateSurrender)],
    ['Maximum split hands', String(rules.maxSplitHands)],
    ['Re-split aces', yesNo(rules.resplitAces)],
    ['Shoe penetration', `${String(rules.penetrationPercent)}%`],
    ['Dealer hole card', 'American hole card, dealer peeks for blackjack'],
    ['Insurance', 'Never taken'],
    ['Player decisions', 'Perfect basic strategy for these rules, generated by an exact solver'],
  ];
}

function targetText(config: ExperimentConfig): string {
  const amount = (target: (typeof TARGET_IDS)[number]) =>
    `${TARGET_MULTIPLES[target].label} (+${money(targetAmount(config.startingBankroll, target))})`;
  switch (config.targetMode) {
    case 'none':
      return 'No target: simulations end at the round limit, bust or block';
    case 'single':
      return config.singleTarget === null
        ? 'Single target'
        : `Single target: ${amount(config.singleTarget)}`;
    case 'compare_all':
      return `Compare all four targets: ${TARGET_IDS.map(amount).join(', ')}; final profit is capped at 2.5x`;
  }
}

export function configurationSection(config: ExperimentConfig): string {
  const settings = table({
    caption: 'Experiment settings',
    headers: ['Setting', 'Value'],
    numericFrom: 2,
    rows: [
      ['Experiment id', config.experimentId],
      ['Experiment seed', String(config.experimentSeed)],
      ['Simulations', count.format(config.simulations)],
      ['Round limit per simulation', count.format(config.roundLimit)],
      ['Starting bankroll', `${money(config.startingBankroll)} ${config.currency}`],
      ['Table minimum', money(config.tableMinimum)],
      ['Base unit', money(config.unit)],
      ['Table maximum', config.tableMaximum === null ? 'None' : money(config.tableMaximum)],
      ['Profit target', targetText(config)],
      [
        'Checkpoints (rounds)',
        config.checkpoints.length === 0
          ? 'None'
          : config.checkpoints.map((round) => count.format(round)).join(', '),
      ],
    ],
  });
  const rules = table({
    caption: 'Table rules',
    headers: ['Rule', 'Setting'],
    numericFrom: 2,
    rows: rulesRows(config.rules),
  });
  const strategies = config.strategies
    .map(({ id, version }) => {
      const info = STRATEGIES[id];
      return `<li><strong>${escapeHtml(info.name)}</strong> <span class="muted">(${escapeHtml(version)})</span>: ${escapeHtml(
        info.rule.replace('{N}', String(config.paroliStreakLength)),
      )} <span class="muted">Main risk: ${escapeHtml(info.mainRisk)}</span></li>`;
    })
    .join('\n');
  return section(
    'configuration',
    'Configuration',
    `${settings}\n${rules}\n<h3>Strategies</h3>\n${paragraph('A betting strategy decides only the size of the next initial bet. Every hand is played with the same perfect basic strategy.')}\n<ul class="strategies">${strategies}</ul>`,
  );
}

export function comparisonSection(strategies: readonly StrategySummary[]): string {
  const rows = strategies.map((s): Cell[] => [
    {
      html: `${escapeHtml(STRATEGIES[s.strategyId].name)}<span class="ci">${escapeHtml(s.strategyVersion)}</span>`,
    },
    count.format(s.simulations),
    withInterval(
      money(s.profitMean),
      s.profitMeanInterval === null
        ? null
        : `${money(s.profitMeanInterval.low)} to ${money(s.profitMeanInterval.high)}`,
    ),
    money(s.profitPercentiles.median),
    money(s.profitPercentiles.p5),
    money(s.profitPercentiles.p95),
    withInterval(
      percent.format(s.profitShare),
      `${percent.format(s.profitShareInterval.low)} to ${percent.format(s.profitShareInterval.high)}`,
    ),
    withInterval(
      rate.format(s.returnPerUnitWagered),
      s.returnPerUnitWageredInterval === null
        ? null
        : `${rate.format(s.returnPerUnitWageredInterval.low)} to ${rate.format(s.returnPerUnitWageredInterval.high)}`,
    ),
    percent.format(s.bustRate),
    percent.format(s.blockRate),
    money(s.averageMaxDrawdown),
    money(s.averageWager),
    money(s.maxWager),
    count.format(s.unavailableActions),
  ]);
  return section(
    'comparison',
    'Comparison under this configuration',
    `${paragraph('Smaller figures under a value are its 95% interval.', 'muted')}\n${table({
      caption: 'Per-strategy results under this configuration, with 95% intervals',
      headers: [
        'Strategy',
        'Simulations',
        'Mean profit',
        'Median',
        '5th pct',
        '95th pct',
        'Ended in profit',
        'Return per unit wagered',
        'Bust rate',
        'Block rate',
        'Avg max drawdown',
        'Avg bet',
        'Max bet',
        'Unavailable actions',
      ],
      rows,
    })}`,
  );
}

function rankingBlock(
  strategies: readonly StrategySummary[],
  goal: Goal,
  heading: string,
  options: RankingOptions,
): string {
  const ranking = rankByGoal(strategies, goal, options);
  const leaderName = STRATEGIES[ranking.entries[0]?.strategyId ?? 'flat'].name;
  const items = ranking.entries
    .map((entry) => {
      const value = formatRankingValue(goal, entry.value);
      const interval =
        entry.interval === null
          ? ''
          : ` <span class="muted">${escapeHtml(range(formatRankingValue(goal, entry.interval.low), formatRankingValue(goal, entry.interval.high)))}</span>`;
      return `<li><strong>${escapeHtml(STRATEGIES[entry.strategyId].name)}</strong> ${escapeHtml(value)}${interval} <span class="muted">${escapeHtml(VERDICT_TEXT[entry.verdict])}</span></li>`;
    })
    .join('');
  const verdict = ranking.clearLeader
    ? `Best under this selected configuration: ${leaderName}.`
    : NO_CLEAR_LEADER;
  return `<div class="ranking"><h3>${escapeHtml(heading)}</h3>${paragraph(`Ranked by: ${GOAL_TEXT[goal].metric}.`, 'muted')}${paragraph(verdict, 'verdict')}<ol>${items}</ol></div>`;
}

export function rankingsSection(
  strategies: readonly StrategySummary[],
  checkpointRounds: readonly number[],
): string {
  const blocks = [
    rankingBlock(strategies, 'overall', GOAL_TEXT.overall.question, {}),
    rankingBlock(strategies, 'minimal_loss', GOAL_TEXT.minimal_loss.question, {}),
    rankingBlock(strategies, 'maximum_win', GOAL_TEXT.maximum_win.question, {}),
    ...TARGET_IDS.map((target) =>
      rankingBlock(
        strategies,
        'target',
        `${GOAL_TEXT.target.question}: ${TARGET_MULTIPLES[target].label}`,
        { target },
      ),
    ),
    ...checkpointRounds.map((round, checkpointIndex) =>
      rankingBlock(
        strategies,
        'checkpoint',
        `${GOAL_TEXT.checkpoint.question}: round ${count.format(round)}`,
        {
          checkpointIndex,
        },
      ),
    ),
  ];
  return section(
    'rankings',
    'Rankings by goal',
    `${paragraph(RANKINGS_NOTE)}\n<div class="rankings">${blocks.join('\n')}</div>`,
  );
}

export function targetsSection(strategies: readonly StrategySummary[]): string {
  const rows = strategies.flatMap((s) =>
    s.targets.map((t): Cell[] => [
      `${STRATEGIES[s.strategyId].name}, ${TARGET_MULTIPLES[t.target].label}`,
      count.format(s.simulations),
      withInterval(
        percent.format(t.hitRate),
        `${percent.format(t.hitRateInterval.low)} to ${percent.format(t.hitRateInterval.high)}`,
      ),
      t.meanRoundsToTarget === null ? '—' : count.format(Math.round(t.meanRoundsToTarget)),
      t.medianRoundsToTarget === null ? '—' : count.format(Math.round(t.medianRoundsToTarget)),
      percent.format(t.bustBefore),
    ]),
  );
  return section(
    'targets',
    'Target attainment',
    `${paragraph('Share of simulations that ever reached each target, even if profit fell back later. Rounds to target count only simulations that reached it.', 'muted')}\n${table(
      {
        caption: 'Target attainment per strategy',
        headers: [
          'Strategy and target',
          'Simulations',
          'Reached',
          'Mean rounds to target',
          'Median rounds',
          'Bust before target',
        ],
        rows,
      },
    )}`,
  );
}

export function checkpointsSection(strategies: readonly StrategySummary[]): string {
  if ((strategies[0]?.checkpoints.length ?? 0) === 0) return '';
  const tables = strategies
    .map((s) =>
      table({
        caption: `${STRATEGIES[s.strategyId].name}: profit and bets at each checkpoint`,
        headers: [
          'Round',
          'Simulations',
          'Mean profit',
          'Median (approx.)',
          '5th–95th pct (approx.)',
          'In profit',
          'Worst',
          'Still playing',
          'Mean bet',
          '95th pct bet',
        ],
        rows: s.checkpoints.map((c): Cell[] => [
          count.format(c.round),
          count.format(c.simulations),
          withInterval(
            money(c.meanProfit),
            c.meanProfitInterval === null
              ? null
              : `${money(c.meanProfitInterval.low)} to ${money(c.meanProfitInterval.high)}`,
          ),
          money(c.approximate.median),
          `${money(c.approximate.p5)} to ${money(c.approximate.p95)}`,
          percent.format(c.profitableShare),
          money(c.worstProfit),
          `${count.format(c.bets.stillPlaying)} (${percent.format(c.bets.stillPlayingShare)})`,
          c.bets.meanBet === null ? '—' : money(c.bets.meanBet),
          c.bets.p95Bet === null ? '—' : money(c.bets.p95Bet),
        ]),
      }),
    )
    .join('\n');
  return section(
    'checkpoints',
    'Checkpoint data',
    `${paragraph('Strategies that stopped earlier are carried forward at their final profit. Percentiles are approximate, from fixed 1%-of-bankroll bins. Bets count only strategies still playing at that round.', 'muted')}\n${tables}`,
  );
}

export function gridSection(
  displayed: readonly (readonly StrategySimulationResult[] | null)[],
  experimentSeed: number,
): string {
  const panels = displayed
    .map((results, index) => {
      const title = `Simulation ${String(index + 1)} · seed ${String(simulationSeed(experimentSeed, index))}`;
      const body =
        results === null
          ? '<p class="muted panel-empty">Not finished (run cancelled)</p>'
          : `<div class="chart panel-chart" data-chart="panel-${String(index)}" role="img" aria-label="${escapeHtml(`Bankroll per strategy in simulation ${String(index + 1)}`)}"></div>`;
      return `<figure class="panel"><figcaption>${escapeHtml(title)}</figcaption>${body}</figure>`;
    })
    .join('\n');
  return section(
    'grid',
    'Simulations side by side',
    `${paragraph('Each panel is one simulation: every strategy played the same cards. Lines end where a strategy stopped, labelled with the stop reason. Drag or scroll inside a panel to zoom.', 'muted')}\n<div class="panels">${panels}</div>`,
  );
}

export function samplesSection(results: ExperimentResults, experimentSeed: number): string {
  const blocks = results.shape.strategies
    .map((strategy, index) => {
      const rows = sampleRows(results, index, experimentSeed);
      const name = STRATEGIES[strategy.id].name;
      return `<details><summary>${escapeHtml(name)} (${count.format(rows.length)} simulations)</summary>${table(
        {
          caption: `Sample simulations for ${name}`,
          headers: [
            'Simulation',
            'Seed',
            'Rounds',
            'Final profit',
            'Max bet',
            'Max drawdown',
            'Stop reason',
          ],
          numericFrom: 2,
          rows: rows.map((row): Cell[] => [
            String(row.simulationId + 1),
            String(row.seed),
            count.format(row.roundsPlayed),
            money(row.netProfit),
            money(row.maxWager),
            money(row.maxDrawdown),
            STOP_LABELS[row.stopReason],
          ]),
        },
      )}</details>`;
    })
    .join('\n');
  return section(
    'samples',
    'Sample simulations',
    `${paragraph('The first finished simulations by number, at most 500 per strategy. Any one can be replayed from the experiment configuration and its seed.', 'muted')}\n${blocks}`,
  );
}
